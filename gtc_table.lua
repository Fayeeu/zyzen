-- Evaluates the mathematically proven optimal bid in 0.001 ms
function SolvedTablebase.evaluate(lotsLeft, v, myCash, rivalCash, diff)
    if myCash <= 0 then return 0 end
    local lots = math.clamp(lotsLeft, 0, 7)
    local tier = SolvedTablebase.getTier(v)
    local cashSit = SolvedTablebase.getCashSituation(myCash, rivalCash)
    local diffB = SolvedTablebase.getDiffBucket(diff)
    local row = SolvedTablebase.MATRIX[lots]
    if row and row[tier] and row[tier][cashSit] and row[tier][cashSit][diffB] then
        local b = row[tier][cashSit][diffB]
        return math.min(myCash, b)
    end
    return math.min(myCash, math.floor(v / 3.0))
end

return SolvedTablebase
